"""회로 시뮬레이터 페이지: 회로도를 직접 그리고 전류가 어디로 얼마나 흐르는지 실시간으로 본다."""
import streamlit as st

from ui import realtime


def render():
    st.title("🔌 회로 시뮬레이터")
    st.caption("부품을 놓고 전선으로 이어 회로를 직접 만들면, 브라우저에서 바로 계산해 **전류가 어느 방향으로 얼마나 흐르는지** "
               "움직이는 점과 숫자로 보여 줍니다. 전선 색은 전압(초록 = +, 빨강 = −)입니다. 값을 바꾸거나 스위치를 누르면 "
               "지금 상태에서 바로 반응하고, ⟲ 버튼으로 처음부터 다시 시작합니다.")
    realtime.render(realtime.circuit_html(), height=1250)
    with st.expander("부품과 계산 방법", expanded=False):
        st.markdown("""
- **전원**: 직류 전압원(+ 표시 단자가 높은 쪽), 교류 전압원 v = Vo + Vm·sin(2πft + 위상), 전류원.
- **수동 소자**: 저항, 전구(R = V정격²/P정격, 전력만큼 밝아짐), 인덕터(v = L·di/dt), 커패시터(i = C·dv/dt).
- **스위치·반도체**: 스위치(클릭으로 열고 닫기), PWM 스위치(주파수·듀티비), 다이오드(순방향 전압 Vf + 도통 저항).
- **DC 전동기**: 전기자 회로 v = Ra·i + La·di/dt + Kφ·ω 와 운동 방정식 J·dω/dt = Kφ·i − Bω − TL 을 함께 풉니다.
- **계기**: 전류계(내부 저항 0), 전압계(내부 저항 ∞). 순시값과 실효값(RMS)을 보여 줍니다.
- **계산**: 수정 절점 해석(MNA)과 후진 오일러 적분을 씁니다. 다이오드·스위치는 켜짐/꺼짐 상태가 맞을 때까지 반복해 풉니다.
  전선마다 흐르는 전류는 각 접점에서 키르히호프 전류 법칙(KCL)으로 나눠 계산합니다.
- **팁**: 인덕터 전류가 흐르는 중에 스위치를 열면 전류가 갈 곳이 없어 매우 높은 전압이 생깁니다 (실제로는 불꽃).
  환류 다이오드를 달아 보세요. 교류 회로나 PWM 처럼 빠른 회로는 재생 속도를 1/100 이하로, 계산 간격을 작게 하세요.
""")
